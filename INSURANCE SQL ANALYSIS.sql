CREATE VIEW Claims_view AS
SELECT
    CLAIM_ID,
    POLICY_ID,
    CUSTOMER_ID,
    CLAIM_TYPE,
    INCIDENT_DATE,
    REPORTED_DATE,
    CLAIM_AMOUNT,
    CLAIM_STATUS,
    SETTLEMENT_AMOUNT,
    PROCESSING_DAYS,
    FRAUD_FLAG AS FRAUD_FLAG_RAW,

    -- Numeric fraud score
    CASE
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'CONFIRMED' THEN 1.00
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'SUSPECTED' THEN 0.60
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'NO' THEN 0.00
        ELSE NULL
    END AS FRAUD_SCORE,

    SOURCE,
    CLAIM_SEVERITY,

    -- Reporting delay
    DATEDIFF(DAY, INCIDENT_DATE, REPORTED_DATE)
        AS REPORTING_DELAY,

    -- Unsettled amount
    CLAIM_AMOUNT - SETTLEMENT_AMOUNT AS UNSETTLED_AMOUNT,

    -- Settlement rate
    CASE
        WHEN CLAIM_AMOUNT > 0
        THEN (SETTLEMENT_AMOUNT * 100.0) / CLAIM_AMOUNT
        ELSE 0
    END AS SETTLEMENT_RATE,

    -- Fraud risk level
    CASE
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'CONFIRMED'
            THEN 'HIGH RISK'
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'SUSPECTED'
            THEN 'MEDIUM RISK'
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'NO'
            THEN 'LOW RISK'
        ELSE 'UNKNOWN'
    END AS FRAUD_RISK_LEVEL,

    -- Standardize fraud flag
    CASE
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'CONFIRMED'
            THEN 'CONFIRMED'
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'SUSPECTED'
            THEN 'SUSPECTED'
        WHEN UPPER(TRIM(FRAUD_FLAG)) = 'NO'
            THEN 'NO'
        ELSE 'UNKNOWN'
    END AS FRAUD_FLAG_STATUS,

    -- Incident date details
    YEAR(INCIDENT_DATE) AS INCIDENT_YEAR,
    MONTH(INCIDENT_DATE) AS INCIDENT_MONTH,
    DATENAME(MONTH, INCIDENT_DATE) AS INCIDENT_MONTH_NAME,

    -- Quarter
    'Q' + CAST(DATEPART(QUARTER, INCIDENT_DATE) AS VARCHAR(1))
        AS INCIDENT_QTR

FROM claims;

SELECT TOP 10 * FROM Claims_view

