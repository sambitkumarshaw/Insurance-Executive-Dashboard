CREATE VIEW Renewals_view AS

SELECT
    RENEWAL_ID,
    POLICY_ID,
    CUSTOMER_ID,
    RENEWAL_DUE_DATE,
    YEAR(RENEWAL_DUE_DATE) AS RENEWAL_DUE_YEAR,
    MONTH(RENEWAL_DUE_DATE) AS RENEWAL_DUE_MONTH,
    DATENAME(MONTH,RENEWAL_DUE_DATE) AS RENEWAL_DUE_MONTH_NAME,
    'Q' + CAST(DATEPART(QUARTER,RENEWAL_DUE_DATE) AS VARCHAR(1)) AS RENEWAL_DUE_QUARTER,
    OLD_PREMIUM,
    NEW_PREMIUM,
    NEW_PREMIUM-OLD_PREMIUM AS PREMIUM_CHANGE_AMOUNT,
    CASE 
        WHEN  OLD_PREMIUM > 0 THEN ((NEW_PREMIUM - OLD_PREMIUM*100.0)/OLD_PREMIUM)
        ELSE NULL
    END AS CALCULATED_PREMIUM_INCREASE_PCT,
CASE
    WHEN PREMIUM_INCREASE_PCT < 0
        THEN 'PREMIUM DECREASE'
    WHEN PREMIUM_INCREASE_PCT = 0
        THEN 'NO CHANGE'
    WHEN PREMIUM_INCREASE_PCT <= 5
        THEN '0-5% INCREASE'
    WHEN PREMIUM_INCREASE_PCT <= 10
        THEN '5-10% INCREASE'
    WHEN PREMIUM_INCREASE_PCT <= 20
        THEN '10-20% INCREASE'
    ELSE '20%+ INCREASE'
END AS PREMIUM_INCREASE_BAND,
PREMIUM_INCREASE_PCT, 
CLAIM_HISTORY_FLAG,
LOYALTY_YEARS,
CASE
    WHEN LOYALTY_YEARS < 2 THEN 'NEW'
    WHEN LOYALTY_YEARS < 5 THEN 'ESTABLISHED'
    WHEN LOYALTY_YEARS < 10 THEN 'LOYAL'
    ELSE 'HIGHLY LOYAL'
END AS LOYALTY_SEGMENT,
RENEWAL_PROBABILITY,
RENEWAL_STATUS,
CONTACT_CHANNEL,
CASE
    WHEN CONTACT_CHANNEL IN ('SMS', 'Email', 'WhatsApp') THEN 'DIGITAL'
    WHEN CONTACT_CHANNEL = 'CALL'  THEN 'VOICE'
    ELSE  'PERSONAL'
END AS CONTACT_CHANNEL_GROUP

FROM renewals;

SELECT * FROM Renewals_view;

