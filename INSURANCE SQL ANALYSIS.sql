    SMOKER_FLAG,
    BMI,
    CASE
        WHEN BMI < 18.5 THEN 'UNDERWEIGHT'
        WHEN BMI < 25 THEN 'NORMAL'
        WHEN BMI < 30 THEN 'OVERWEIGHT'
        WHEN BMI < 35 THEN 'OBESE CLASS I'
        WHEN BMI < 40 THEN 'OBESE CLASS II'
        ELSE 'OBESE CLASS III'
    END AS BMI_CATEGORY,
    OCCUPATION_RISK,
    CREDIT_SCORE,
    UNDERWRITING_SCORE,
    DECISION,
              -- Convert loading to percentage
    FORMAT(PREMIUM_LOADING_PCT / 100.0, 'P2') AS PREMIUM_LOADING_PCT
FROM underwriting;

