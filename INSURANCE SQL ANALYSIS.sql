    WHEN DATEDIFF(YEAR,CUSTOMER_SINCE,GETDATE()) < 2 THEN 'NEW'
    WHEN DATEDIFF(YEAR,CUSTOMER_SINCE,GETDATE()) < 5 THEN 'ESTABLISHED'
