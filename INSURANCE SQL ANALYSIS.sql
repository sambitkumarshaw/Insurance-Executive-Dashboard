CREATE VIEW Premiums_view as

SELECT
    PREMIUM_TXN_ID,
    POLICY_ID,
    CUSTOMER_ID,

    -- Date conversion
    TRY_CONVERT(DATE, DUE_DATE, 103) AS DUE_DATE,
                 -- ---- -- (103 — The date format code for DD/MM/YYYY.)                       
    -- Convert 1900-01-01 to NULL           
    NULLIF(
        TRY_CONVERT(DATE, PAID_DATE, 103),
        '1900-01-01'
    ) AS PAID_DATE,

    -- Numeric conversions
    TRY_CONVERT(INT, PREMIUM_AMOUNT) AS PREMIUM_AMOUNT,
    PAYMENT_STATUS,
    PAYMENT_METHOD,
    TRY_CONVERT(INT, PAYMENT_DELAY_DAYS) AS PAYMENT_DELAY_DAYS,
    TRY_CONVERT(DECIMAL(10,2), CHANNEL_COST) AS CHANNEL_COST,

    -- Payment delay segmentation
    CASE
        WHEN TRY_CONVERT(INT, PAYMENT_DELAY_DAYS) IS NULL
            THEN 'UNKNOWN'
        WHEN TRY_CONVERT(INT, PAYMENT_DELAY_DAYS) <= 0
            THEN 'ON TIME'
        WHEN TRY_CONVERT(INT, PAYMENT_DELAY_DAYS) <= 7
            THEN '1-7 DAYS LATE'
        WHEN TRY_CONVERT(INT, PAYMENT_DELAY_DAYS) <= 30
            THEN '8-30 DAYS LATE'
        ELSE '30+ DAYS LATE'
    END AS PAYMENT_DELAY_BAND,

    -- Payment status grouping
    CASE
        WHEN PAYMENT_STATUS IN ('PAID', 'COMPLETED')
            THEN 'PAID'
        WHEN PAYMENT_STATUS IN ('PENDING', 'OVERDUE')
            THEN 'PENDING'
        ELSE 'FAILED'
    END AS PAYMENT_STATUS_GROUP,

    -- Channel cost percentage
    CASE
        WHEN TRY_CONVERT(DECIMAL(12,2), PREMIUM_AMOUNT) > 0
        THEN FORMAT(
            TRY_CONVERT(DECIMAL(10,2), CHANNEL_COST)
            / TRY_CONVERT(DECIMAL(12,2), PREMIUM_AMOUNT),
            'P2'
        )
        ELSE NULL
    END AS CHANNEL_COST_PCT,

    -- Net premium
    TRY_CONVERT(DECIMAL(12,2), PREMIUM_AMOUNT)
        - TRY_CONVERT(DECIMAL(12,2), CHANNEL_COST)
        AS NET_PREMIUM,

    -- Payment method grouping
    CASE
        WHEN PAYMENT_METHOD IN
            ('UPI', 'DEBIT CARD', 'CC', 'NET BANKING')
            THEN 'DIGITAL'
        WHEN PAYMENT_METHOD IN
            ('CASH', 'CHEQUE', 'AUTO')
            THEN 'NON-DIGITAL'
        ELSE 'OTHER'
    END AS PAYMENT_METHOD_GROUP,

    -- Due date attributes
    YEAR(TRY_CONVERT(DATE, DUE_DATE, 103)) AS DUE_YEAR,
    MONTH(TRY_CONVERT(DATE, DUE_DATE, 103)) AS DUE_MONTH,

    -- Paid date attributes
 YEAR(NULLIF(TRY_CONVERT(DATE, PAID_DATE, 103),'1900-01-01')) AS PAID_YEAR,

 MONTH(NULLIF(TRY_CONVERT(DATE, PAID_DATE, 103),'1900-01-01')) AS PAID_MONTH

FROM PREMIUMS;

